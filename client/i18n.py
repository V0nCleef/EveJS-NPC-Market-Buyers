def _nmb_response_error(response):
    key = response.get('errorKey') or 'request_failed'
    if key not in ('permission_error', 'revision_error', 'setting_range', 'boolean_error',
                   'interval_error', 'warning_error', 'batch_range_error', 'invalid_setting',
                   'request_invalid', 'session_not_ready'):
        key = 'request_failed'
    params = dict(response.get('errorParams') or {})
    if 'setting' in params:
        params['setting'] = _nmb_tr(_NMB_CONFIG_LABELS.get(params['setting'], 'configure_tab'))
    try:
        return _nmb_tr(key, **params)
    except (ValueError, KeyError, TypeError):
        return _nmb_tr('request_failed')


def _nmb_error_text(error):
    if isinstance(error, _NmbUiError):
        return unicode(error)
    if 'another window' in unicode(error):
        return _nmb_tr('revision_error')
    return _nmb_tr('request_failed')


def _nmb_preview_message(preview, config=None):
    reason = preview.get('reason') or ('eligible' if preview.get('eligible') else 'missing_quote')
    if reason == 'eligible':
        reason = {'high': 'high_price', 'low': 'low_price'}.get(preview.get('warning'), 'fair_price')
    key = {'disabled': 'buying_paused', 'no_allowance': 'demand_limit'}.get(reason, reason)
    if key not in ('missing_quote', 'missing_average', 'invalid_order', 'stale_quote', 'thin_market', 'buying_paused',
                   'price_cap', 'demand_limit', 'budget_limit', 'high_price', 'low_price',
                   'fair_price', 'settlement_unavailable', 'immediate_sale', 'zero_chance'):
        key = 'preview_unavailable'
    percent = _nmb_number(preview.get('pricePercent'), 100)
    return _nmb_tr(key, above=percent-100, below=100-percent,
                   cap=_nmb_number((config or {}).get('maxPricePercent'), 125))


