def _nmb_language(value=None):
    if value is None:
        try:
            import localization
            value = localization.GetLanguageID()
        except Exception:
            pass
    if not value:
        context = globals().get('_nmb_context') or {}
        session = context.get('session') or getattr(_nmb_i18n_builtins, 'session', None)
        value = getattr(session, 'languageID', None) or getattr(session, 'languageId', None)
    code = unicode(value or 'en').strip().lower().replace('_', '-').split('-')[0]
    code = {'cn': 'zh', 'jp': 'ja'}.get(code, code)
    return code if code in _NMB_LANGUAGES else 'en'


def _nmb_tr(key, **values):
    template = _NMB_TRANSLATIONS[_nmb_language()].get(key, _NMB_TRANSLATIONS['en'].get(key))
    if template is None:
        template = _NMB_TRANSLATIONS[_nmb_language()]['request_failed']
    return template.format(**values) if values else template


